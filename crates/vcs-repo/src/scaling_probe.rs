//! Benchmark access to crate-private structures (feature `scaling-probe`; used only by
//! `vcs-bench`'s `scalebench`, see scripts/scaling/). Builds synthetic AGI5 / reach-cache /
//! path-filter files of a chosen size directly (no real files), and exposes the real readers.
//! Nothing here is used by the product.

use crate::index5::{self, Base5};
use crate::{pathbloom, reachcache};
use std::io::Write;
use std::path::Path;
use vcs_objects::ObjectId;

fn mix(mut x: u64) -> u64 {
    x = x.wrapping_add(0x9E37_79B9_7F4A_7C15);
    x = (x ^ (x >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^ (x >> 31)
}

/// The `i`-th of `n` ids in strictly increasing order, uniformly spread over the 256-bit space
/// (top 64 bits: evenly spaced plus hash jitter; the other 192 bits: pseudo-random). Lets a
/// sorted id table of any size be generated by streaming, with no sort.
pub fn sorted_id(i: u64, n: u64) -> [u8; 32] {
    let stride = ((1u128 << 64) / n as u128) as u64;
    let base = (i as u128 * (1u128 << 64) / n as u128) as u64;
    let jitter = if stride > 2 { mix(i ^ 0xA5A5) % (stride / 2) } else { 0 };
    let mut out = [0u8; 32];
    out[..8].copy_from_slice(&base.wrapping_add(jitter).to_be_bytes());
    let mut s = mix(i.wrapping_mul(0x2545_F491_4F6C_DD1D));
    for k in 0..3 {
        s = mix(s);
        out[8 + k * 8..16 + k * 8].copy_from_slice(&s.to_be_bytes());
    }
    out
}

/// Path of AGI5 synthetic record `i` of `n`: sorted numerically, first byte spread over a..z.
pub fn agi5_path(i: u64, n: u64) -> String {
    let dirs = n.div_ceil(100).max(1);
    let d = i / 100;
    let c = (b'a' + (d * 26 / dirs) as u8) as char;
    format!("{c}{d:09}/f{:02}.c", i % 100)
}

/// Write a synthetic `AGI5` base file of `n` records. Returns the file size.
pub fn agi5_write(path: &Path, n: usize) -> std::io::Result<u64> {
    const REC: usize = index5::REC;
    const RECS_OFF: usize = 1152;
    let mut out: Vec<u8> = Vec::with_capacity(RECS_OFF + n * REC + n * 16 + 4096);
    out.resize(RECS_OFF, 0);
    let mut heap: Vec<u8> = Vec::with_capacity(n * 16);
    let mut fan = [0u32; 257];
    for i in 0..n {
        let p = agi5_path(i as u64, n as u64);
        let pb = p.as_bytes();
        fan[pb[0] as usize + 1] += 1;
        let id = sorted_id(i as u64, n as u64);
        out.extend_from_slice(&id);
        out.extend_from_slice(&(1000 + (i as u64 % 5000)).to_le_bytes());
        out.extend_from_slice(&(1_700_000_000_000_000_000u64 + i as u64).to_le_bytes());
        out.extend_from_slice(&(1_700_000_000_000_000_000u64 + i as u64).to_le_bytes());
        out.extend_from_slice(&(heap.len() as u32).to_le_bytes());
        out.extend_from_slice(&(pb.len() as u16).to_le_bytes());
        out.push(1);
        out.push(0);
        heap.extend_from_slice(pb);
    }
    for i in 1..257 {
        fan[i] += fan[i - 1];
    }
    for (i, f) in fan.iter().enumerate() {
        out[64 + i * 4..64 + i * 4 + 4].copy_from_slice(&f.to_le_bytes());
    }
    out.extend_from_slice(&heap);
    let tree_len = 1usize;
    out.push(0); // cache-tree section: count varint 0
    let sums_off = out.len();
    let nchunks = sums_off.div_ceil(index5::CHUNK);
    out[0..4].copy_from_slice(b"AGI5");
    out[4] = 1;
    out[8..16].copy_from_slice(&1u64.to_le_bytes());
    out[16..24].copy_from_slice(&1u64.to_le_bytes());
    out[24..32].copy_from_slice(&(n as u64).to_le_bytes());
    out[32..40].copy_from_slice(&(heap.len() as u64).to_le_bytes());
    out[40..48].copy_from_slice(&(tree_len as u64).to_le_bytes());
    out[48..56].copy_from_slice(&(nchunks as u64).to_le_bytes());
    let hs = index5::sum64(&out[..56]);
    out[56..64].copy_from_slice(&hs.to_le_bytes());
    let mut st = Vec::with_capacity(nchunks * 8);
    for c in 0..nchunks {
        st.extend_from_slice(&index5::sum64(&out[c * index5::CHUNK..((c + 1) * index5::CHUNK).min(sums_off)]).to_le_bytes());
    }
    out.extend_from_slice(&st);
    out.extend_from_slice(&index5::sum64(&st).to_le_bytes());
    std::fs::write(path, &out)?;
    Ok(out.len() as u64)
}

/// A real, mmap-opened AGI5 base.
pub struct Agi5(Base5);

impl Agi5 {
    pub fn open(path: &Path) -> Result<Agi5, String> {
        Base5::open(path).map(Agi5).map_err(|e| e.to_string())
    }
    pub fn n(&self) -> usize {
        self.0.n
    }
    pub fn find(&self, p: &str) -> bool {
        self.0.find(p).ok().flatten().is_some()
    }
    /// Visit every record in order with the same path validation the status scan does.
    pub fn scan(&self) -> Result<u64, String> {
        let mut sum = 0u64;
        self.0
            .each(0, self.0.n, |_, e| {
                sum = sum.wrapping_add(e.size);
                Ok(())
            })
            .map_err(|e| e.to_string())?;
        Ok(sum)
    }
    pub fn verify_all(&self) -> Result<(), String> {
        self.0.verify_all().map_err(|e| e.to_string())
    }
}

/// Write a synthetic `gc-reach` cache: `ns` sorted ids, every 4th marked, a few roots.
pub fn reach_write(path: &Path, ns: usize, nroots: usize) -> std::io::Result<u64> {
    // streamed (no per-object vectors), byte for byte what `reachcache::encode` writes
    let mut f = std::io::BufWriter::with_capacity(8 << 20, std::fs::File::create(path)?);
    let mut h = blake3::Hasher::new();
    let mut w = |f: &mut std::io::BufWriter<std::fs::File>, b: &[u8]| -> std::io::Result<()> {
        h.update(b);
        f.write_all(b)
    };
    w(&mut f, b"AGRB")?;
    w(&mut f, &[1u8])?;
    w(&mut f, &(ns as u32).to_le_bytes())?;
    w(&mut f, &(nroots as u32).to_le_bytes())?;
    for i in 0..ns as u64 {
        w(&mut f, &sorted_id(i, ns as u64))?;
    }
    for which in 0..2 {
        let mut i = 0usize;
        while i < ns {
            let mut byte = 0u8;
            for b in 0..8 {
                let k = i + b;
                let set = k < ns && if which == 0 { k % 4 != 3 } else { k % 1000 == 0 };
                if set {
                    byte |= 1 << b;
                }
            }
            w(&mut f, &[byte])?;
            i += 8;
        }
    }
    for i in 0..nroots {
        let at = (i * (ns / nroots.max(1)).max(1)).min(ns - 1);
        w(&mut f, &sorted_id(at as u64, ns as u64))?;
    }
    f.write_all(h.finalize().as_bytes())?;
    f.flush()?;
    Ok(std::fs::metadata(path)?.len())
}

pub struct Reach(reachcache::ReachCache);

impl Reach {
    /// Map the file (O(1)); nothing but the header is read.
    pub fn load(path: &Path) -> Option<Reach> {
        reachcache::ReachCache::open(path).map(Reach)
    }
    /// Map the file and checksum all of it (what gc does at start, and fsck).
    pub fn load_verified(path: &Path) -> Option<Reach> {
        reachcache::ReachCache::open_verified(path).map(Reach)
    }
    /// The whole-file checksum of an opened file.
    pub fn verify_full(&self) -> bool {
        self.0.verify_full()
    }
    pub fn marked(&self, id: &[u8; 32]) -> bool {
        self.0.marked(&ObjectId::from_bytes(*id))
    }
    pub fn scanned(&self, id: &[u8; 32]) -> bool {
        self.0.scanned(&ObjectId::from_bytes(*id))
    }
    pub fn roots_within(&self, roots: &[[u8; 32]]) -> bool {
        let r: Vec<ObjectId> = roots.iter().map(|b| ObjectId::from_bytes(*b)).collect();
        self.0.roots_within(&r)
    }
}

/// Changed-path filter of `paths` (file paths); None when over the limit.
pub fn bloom_build(paths: &[String]) -> Option<Vec<u8>> {
    pathbloom::build_filter(paths.iter())
}
pub fn bloom_may_contain(f: &[u8], path: &str) -> bool {
    pathbloom::may_contain(&Some(f.to_vec()), path)
}
pub const BLOOM_MAX_PATHS: usize = pathbloom::MAX_PATHS;

/// Write a synthetic per-zone path-filter file for `count` commits, one parent filter of `flen` bytes each.
pub fn pathfilter_write(path: &Path, count: usize, flen: usize) -> std::io::Result<u64> {
    let mut f = std::io::BufWriter::new(std::fs::File::create(path)?);
    let mut h = blake3::Hasher::new();
    let w = |h: &mut blake3::Hasher, f: &mut std::io::BufWriter<std::fs::File>, b: &[u8]| -> std::io::Result<()> {
        h.update(b);
        f.write_all(b)
    };
    w(&mut h, &mut f, b"AGPF")?;
    w(&mut h, &mut f, &[1u8])?;
    w(&mut h, &mut f, &(count as u32).to_le_bytes())?;
    for i in 0..count as u64 {
        w(&mut h, &mut f, &sorted_id(i, count as u64))?;
    }
    let rec = 1 + 4 + flen;
    for i in 0..count {
        w(&mut h, &mut f, &((i * rec) as u32).to_le_bytes())?;
    }
    let body = vec![0xA5u8; flen];
    for _ in 0..count {
        w(&mut h, &mut f, &[1u8])?;
        w(&mut h, &mut f, &(flen as u32).to_le_bytes())?;
        w(&mut h, &mut f, &body)?;
    }
    f.write_all(h.finalize().as_bytes())?;
    f.flush()?;
    Ok(std::fs::metadata(path)?.len())
}

pub struct PathFilters(pathbloom::PathBlooms);

impl PathFilters {
    pub fn load(path: &Path) -> PathFilters {
        PathFilters(pathbloom::PathBlooms::open(path))
    }
    pub fn loaded(&self) -> bool {
        self.0.has_file()
    }
    /// Checksum and validate the whole file (fsck).
    pub fn verify_full(&self) -> bool {
        self.0.verify_full()
    }
    pub fn get(&self, id: &[u8; 32]) -> bool {
        self.0.get(&ObjectId::from_bytes(*id)).is_some()
    }
}
